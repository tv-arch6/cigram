// شروط الاستخدام وسياسة الخصوصية.
// عند تعديل النص تعديلاً جوهرياً غيّر TERMS_VERSION: كل مستخدم سيُطلب منه الموافقة على النسخة الجديدة في صفحة «حسابي».
import { CONFIG } from './config.js';
import { esc } from './util.js';

export const TERMS_VERSION = '2026-10-26';
const UPDATED = '٢٦ أكتوبر ٢٠٢٦';

function contactLine() {
  const email = String(CONFIG.contactEmail || '').trim();
  return email
    ? `راسلنا على <a href="mailto:${esc(email)}" dir="ltr">${esc(email)}</a>.`
    : 'تواصل معنا من قسم «المساعدة والدعم» في تطبيق سيكرام.';
}

export function renderTerms(el, ctx) {
  const name = esc(CONFIG.siteName);
  el.innerHTML = `
    <article class="page narrow legal">
      <h1 class="page-title">الشروط والخصوصية</h1>
      <p class="legal-meta">آخر تحديث: ${UPDATED}</p>
      <nav class="legal-toc" aria-label="أقسام الصفحة">
        <a href="#/terms">شروط الاستخدام</a>
        <a href="#/terms?s=privacy">سياسة الخصوصية</a>
      </nav>

      <section id="terms-of-use" class="panel">
        <h2>شروط الاستخدام</h2>
        <h3>١. الموافقة</h3>
        <p>باستخدامك ${name} (التطبيق أو الموقع) أو بإنشاء حساب فيه، فأنت توافق على هذه الشروط. إذا لم توافق عليها فلا تستخدم الخدمة.</p>
        <h3>٢. حسابك</h3>
        <ul>
          <li>أدخل معلومات صحيحة عند إنشاء الحساب، سواء بالبريد الإلكتروني أو بحساب Google.</li>
          <li>أنت مسؤول عن سرية كلمة المرور وعن كل ما يحدث من خلال حسابك. أبلغنا فوراً إذا شككت أن أحداً دخل إليه.</li>
          <li>الحساب شخصي ولا يجوز بيعه أو مشاركته مقابل مال.</li>
          <li>يحق لنا إيقاف أي حساب يسيء استخدام الخدمة أو يخالف هذه الشروط.</li>
        </ul>
        <h3>٣. الاستخدام المسموح</h3>
        <ul>
          <li>الخدمة للمشاهدة الشخصية فقط، وليست للاستخدام التجاري.</li>
          <li>لا يجوز نسخ المحتوى أو تحميله لإعادة نشره، ولا إعادة بثه أو بيعه.</li>
          <li>لا يجوز محاولة اختراق الخدمة أو تعطيلها، ولا إنشاء حسابات أو طلبات آلية.</li>
        </ul>
        <h3>٤. المحتوى</h3>
        <p>المحتوى معروض كما هو، وقد يتغير أو يُحذف في أي وقت. إذا كنت صاحب حقوق لمحتوى معروض وتريد إزالته، ${contactLine()} وسنراجع طلبك ونزيله عند ثبوت الحق.</p>
        <h3>٥. الإعلانات</h3>
        <p>الموقع لا يعرض أي إعلانات (لا داخل المشغل ولا في الصفحات). قد تعرض نسخة التطبيق المجانية إعلانات لتغطية التكاليف، وتختفي بالاشتراك في Cigram Plus.</p>
        <h3>٦. حدود المسؤولية</h3>
        <p>نقدم الخدمة «كما هي» ونعمل على أن تكون متاحة ومستقرة، لكننا لا نضمن خلوها من الانقطاع أو الأخطاء، ولا نتحمل أي ضرر غير مباشر ينتج عن استخدامها.</p>
        <h3>٧. تعديل الشروط</h3>
        <p>قد نعدّل هذه الشروط. عند أي تعديل مهم سنطلب موافقتك على النسخة الجديدة عند دخولك إلى حسابك.</p>
      </section>

      <section id="privacy" class="panel">
        <h2>سياسة الخصوصية</h2>
        <h3>ما الذي نجمعه</h3>
        <ul>
          <li><strong>عند إنشاء الحساب بالبريد:</strong> الاسم، البريد الإلكتروني، كلمة المرور (نحفظها مشفّرة ولا يستطيع أحد قراءتها)، والجنس إن اخترته.</li>
          <li><strong>عند الدخول بحساب Google:</strong> الاسم، البريد الإلكتروني، صورة الحساب، ومعرّف حسابك في Google. لا نحصل على كلمة مرور Google أبداً.</li>
          <li><strong>داخل الخدمة:</strong> صورة الحساب إن رفعتها، وإعجاباتك بالأفلام والمسلسلات.</li>
          <li><strong>للأمان:</strong> وقت الدخول وعنوان IP، لحماية الحسابات ومنع المحاولات المتكررة.</li>
          <li><strong>إحصاءات الاستخدام:</strong> بيانات عامة عن استخدام التطبيق لتحسينه.</li>
        </ul>
        <p>في الموقع، سجل المشاهدة وإعدادات الترجمة والقائمة محفوظة في متصفحك فقط ولا تُرسل إلينا.</p>
        <h3>كيف نستخدمها</h3>
        <p>لتشغيل حسابك وتسجيل دخولك، ولحماية الخدمة من إساءة الاستخدام، ولتحسين التطبيق والموقع.</p>
        <h3>مع من نشاركها</h3>
        <p>لا نبيع بياناتك. نستخدم مزودي خدمات يعملون لصالحنا فقط: Cloudflare لاستضافة الخدمة وقاعدة البيانات، وGoogle لتسجيل الدخول وللإشعارات. شركاء الإعلانات (مثل Google AdMob في التطبيق) قد يجمعون معرّفات الجهاز وفق سياساتهم الخاصة.</p>
        <h3>حذف بياناتك</h3>
        <p>تستطيع حذف حسابك في أي وقت من قسم الحساب في التطبيق أو من صفحة «حسابي» في الموقع. الحذف يزيل حسابك وإعجاباتك نهائياً.</p>
        <h3>الأمان</h3>
        <p>كل الاتصالات مشفّرة (HTTPS)، وكلمات المرور محفوظة مشفّرة بطريقة لا يمكن عكسها.</p>
        <h3>الأطفال</h3>
        <p>الخدمة غير موجّهة لمن هم دون ١٣ عاماً.</p>
        <h3>التواصل</h3>
        <p>لأي سؤال عن خصوصيتك أو لطلب حذف بياناتك: ${contactLine()}</p>
      </section>
    </article>`;
  document.title = `الشروط والخصوصية - ${CONFIG.siteName}`;
  if (ctx && ctx.query && ctx.query.get('s') === 'privacy') {
    requestAnimationFrame(() => {
      const target = el.querySelector('#privacy');
      if (target) window.scrollTo({ top: target.getBoundingClientRect().top + window.scrollY - 80 });
    });
  }
  return {};
}
